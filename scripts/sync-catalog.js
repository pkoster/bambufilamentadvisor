'use strict';
// Usage: node scripts/sync-catalog.js   (Node 18+)
// Fetches the current Bambu color table and writes data/catalog.js.
const fs = require('fs');
const path = require('path');
const { buildCatalog, CATALOG_SOURCE } = require('../src/catalogsync.js');

(async () => {
  const res = await fetch(CATALOG_SOURCE);
  if (!res.ok) throw new Error(`Download failed: HTTP ${res.status}`);
  const catalog = buildCatalog(await res.json());
  const meta = { source: CATALOG_SOURCE, synced: new Date().toISOString().slice(0, 10) };
  const body = 'const CATALOG_META = ' + JSON.stringify(meta) + ';\nconst CATALOG = [\n'
    + catalog.map(c => '  ' + JSON.stringify(c)).join(',\n') + '\n];\n';
  fs.writeFileSync(path.join(__dirname, '..', 'data', 'catalog.js'), '// Generated by scripts/sync-catalog.js — do not edit by hand.\n' + body);
  console.log(`${catalog.length} colors written to data/catalog.js.`);
})().catch(e => { console.error(e.message); process.exit(1); });
