// ---------- Heatmaps: distance from grid point to the nearest color ----------
// The hidden dimension (L* in the top view, hue in the side view) is summarized with max or average.
const RAMP = ['#fff7ec', '#fdd49e', '#fc8d59', '#d7301f', '#7f0000'];
const rampColor = t => {
  const x = Math.max(0, Math.min(1, t)) * (RAMP.length - 1), i = Math.min(Math.floor(x), RAMP.length - 2), f = x - i;
  const p = h => [1, 3, 5].map(k => parseInt(RAMP[h].slice(k, k + 2), 16));
  const [u, v] = [p(i), p(i + 1)];
  return 'rgb(' + u.map((c, k) => Math.round(c + (v[k] - c) * f)).join(',') + ')';
};
let heatMode = 'max';
// Upper bound of the color scale: for a reasonable selection (3+ colors) the worst-covered spot sits
// around 40–50 (ΔE2000) or 100–130 (ΔE76).
const HEAT_MAX = { de2000: 50, de76: 120 };
document.getElementById('heatMode').addEventListener('change', e => { heatMode = e.target.value; render(); });
