// ---------- Rainbow bar: owned + advised colors in one row, in a familiar order ----------
// Chromatic colors by hue (angle in Lab, 0° = red, increasing as red-orange-yellow-green-cyan-blue-purple).
// Near-neutral colors (white/gray/black) have no meaningful hue and sit apart, from black to white.
const NEUTRAL_CHROMA = 8; // threshold between "color" and "shade of gray"
// Layout of the bar: 70% hue wheel, 5% gap, 25% white → black through gray.
const HUE_PART = 70, GAP_PART = 5, GRAY_PART = 25;
const CHIP = 26, CHIP_GAP = 2, ADVICE_INSET = 2; // px; advice chips are a bit smaller all around

const hueOf = c => (Math.atan2(c.b, c.a) * 180 / Math.PI + 360) % 360;
const RED_HUE = (() => { const { a, b } = hexToLab('FF0000'); return hueOf({ a, b }); })(); // ≈ 40°

// Putting a hue wheel on a straight bar needs a cut somewhere. We put it right before red, so the bar
// starts with red on the left and runs rightward through orange, yellow, green, blue and violet, all the
// way to purple, magenta and pink. Within that zone we cut at the emptiest point in the catalog, so no
// color family gets split down the middle.
const CUT_ZONE = 25; // degrees below pure red within which the cut may fall
let RAINBOW_CUT = RED_HUE - CUT_ZONE;
function computeRainbowCut() {
  const hues = catalogAll
    .filter(e => e.hex.length === 1)
    .map(e => hexToLab(e.hex[0]))
    .filter(lab => Math.hypot(lab.a, lab.b) >= NEUTRAL_CHROMA)
    .map(hueOf)
    .sort((x, y) => x - y);
  if (hues.length < 2) return;
  // Only cut just below pure red: that way the bar starts with red, and the pink shades — which sit just
  // below red in hue — shift to the far right end, next to magenta, where they belong.
  const inCutZone = h => h >= RED_HUE - CUT_ZONE && h <= RED_HUE;
  let best = null;
  for (let i = 0; i < hues.length; i++) {
    const from = hues[i], to = hues[(i + 1) % hues.length] + (i + 1 === hues.length ? 360 : 0);
    const mid = (from + (to - from) / 2) % 360;
    if (!inCutZone(mid)) continue;
    if (!best || to - from > best.size) best = { size: to - from, mid };
  }
  if (best) RAINBOW_CUT = best.mid;
}

// Where does a color belong on the bar? Chromatic colors by their hue within the rainbow section,
// near-neutral colors by their lightness within the grayscale section (white on the left, black on the right).
function barPositionPct(c) {
  if (c.C < NEUTRAL_CHROMA) return HUE_PART + GAP_PART + (100 - c.L) / 100 * GRAY_PART;
  return ((hueOf(c) - RAINBOW_CUT + 360) % 360) / 360 * HUE_PART;
}

const rainbowEl = document.getElementById('rainbowStrip');
function drawRainbowBar() {
  const set = visibleSel().concat(suggested);
  rainbowEl.replaceChildren();
  rainbowEl.style.height = '';
  if (!set.length) return;

  // Each chip sits right above its own color on the bar. If two chips would overlap, the second one
  // shifts up a row: the bottom row always stays as close to the bar as possible.
  const width = rainbowEl.clientWidth || 800;
  // A chip stays within the bar it belongs to: colors within the hue bar, grays within the gray bar.
  // Without that limit, white (sitting right at the left edge of the gray bar) would for example stick
  // out halfway into the empty gap between the two bars.
  const bounds = c => (c.C < NEUTRAL_CHROMA
    ? [(HUE_PART + GAP_PART) / 100 * width, width]
    : [0, HUE_PART / 100 * width]);
  const placed = set
    .map(c => ({ c, x: barPositionPct(c) / 100 * width }))
    .sort((p, q) => p.x - q.x);
  const rowRight = []; // right edge of the last-placed chip per row
  let rows = 1;
  for (const p of placed) {
    const [lo, hi] = bounds(p.c);
    const left = Math.min(Math.max(p.x - CHIP / 2, lo), hi - CHIP);
    let row = 0;
    while (rowRight[row] != null && left < rowRight[row] + CHIP_GAP) row++;
    rowRight[row] = left + CHIP;
    p.left = left;
    p.row = row;
    rows = Math.max(rows, row + 1);
  }
  rainbowEl.style.height = `${rows * (CHIP + CHIP_GAP)}px`;

  for (const { c, left, row } of placed) {
    const sug = suggested.includes(c);
    const chip = document.createElement('div');
    chip.className = 'chip ' + (sug ? 'adv' : 'owned');
    chip.dataset.id = c.id;
    chip.style.background = '#' + c.hex;
    // Advice chips sit at the same height as the rest, but are a bit smaller all around so they stand out.
    const inset = sug ? ADVICE_INSET : 0;
    chip.style.left = `${left + inset}px`;
    chip.style.bottom = `${row * (CHIP + CHIP_GAP) + inset}px`;
    chip.style.width = chip.style.height = `${CHIP - 2 * inset}px`;
    chip.title = (sug ? 'Advice: ' : '') + tip(c);
    rainbowEl.appendChild(chip);
  }
}
