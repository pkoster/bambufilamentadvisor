// Recognizes Bambu color numbers (5 digits, e.g. 10300) and SKU codes (e.g. A00-A0 or GFA00-A0) in
// arbitrary text.
function importCodes(text) {
  const tokens = new Set((text.match(/\b\d{5}\b|\b(?:GF)?[A-Za-z]\d{2}-[A-Za-z0-9]{1,3}\b/g) || [])
    .map(t => t.toUpperCase().replace(/^GF(?=[A-Z]\d{2}-)/, '')));
  // Codes across all materials: without a match in the current material, we switch to the material with
  // the most matches.
  const all = new Map();
  for (const e of catalogAll) for (const k of [e.code, e.sku.toUpperCase()]) all.set(k, (all.get(k) || []).concat(e));
  const perMat = new Map();
  for (const t of tokens) for (const e of all.get(t) || []) perMat.set(e.material, (perMat.get(e.material) || 0) + 1);
  let switched = null;
  if (perMat.size && !perMat.get(material)) {
    switched = [...perMat].sort((p, q) => q[1] - p[1])[0][0];
    setMaterial(switched);
  }
  // Every recognized color gets selected for its own material — even if that isn't the one currently
  // shown (e.g. an order with both PLA and PETG). For the active material that happens directly in the
  // live `selected` set; for the rest, straight into that material's stored selection, so it's already
  // there once you switch to it. The "loaded" count is therefore the total across all materials, not
  // just the active one.
  const added = new Set(), already = new Set(), multi = [], unknown = [];
  for (const t of tokens) {
    const hits = all.get(t);
    if (!hits) { unknown.push(t); continue; }
    for (const e of hits) {
      if (e.hex.length !== 1) { multi.push(t); continue; }
      const key = `${e.material}::${e.code}`;
      if (e.material === material) {
        const c = colors.find(x => x.code === e.code);
        (selected.has(c.id) ? already : added).add(key);
        selected.add(c.id); active.add(c.series); ignored.delete(c.id);
      } else {
        const set = selByMaterial.get(e.material) || new Set();
        (set.has(e.code) ? already : added).add(key);
        set.add(e.code);
        selByMaterial.set(e.material, set);
      }
    }
  }
  suggested = suggested.filter(c => !selected.has(c.id));
  const msg = [`${added.size} filament${added.size === 1 ? '' : 's'} loaded`];
  if (switched) msg.unshift(`switched material to ${switched}`);
  if (already.size) msg.push(`${already.size} already selected`);
  if (multi.length) msg.push(`${multi.length} multi-color (skipped): ${multi.join(', ')}`);
  if (unknown.length) msg.push(`filament code not in catalog: ${unknown.join(', ')}`);
  if (!tokens.size) msg[0] = 'no product codes found in the text';
  return msg.join('\n');
}
