function renderInfo() {
  const adv = document.getElementById('advice');
  const label = c => `<i style="background:#${c.hex}"></i>${c.series} – ${c.name} <b>${c.code}</b>`;
  let html = '';
  if (suggested.length) {
    html += '<ol>' + suggested.map(c => `<li data-id="${c.id}">${label(c)}<button class="ign" data-ignore="${c.id}" title="Ignore: don't advise this filament">🚫</button></li>`).join('') + '</ol>';
  }
  if (ignored.size) {
    html += '<div class="ignHead">Ignored</div><ul class="ignList">'
      + [...ignored].sort((x, y) => x - y).map(id => colors[id]).map(c => `<li data-id="${c.id}">${label(c)}<button class="ign" data-unignore="${c.id}" title="Stop ignoring this filament">↩</button></li>`).join('')
      + '</ul>';
  }
  adv.innerHTML = html;
}
document.getElementById('advice').addEventListener('click', e => {
  const ig = e.target.closest('[data-ignore]');
  if (ig) return setIgnored(+ig.dataset.ignore, true);
  const un = e.target.closest('[data-unignore]');
  if (un) return setIgnored(+un.dataset.unignore, false);
  const li = e.target.closest('li');
  if (li && !li.closest('.ignList')) toggle(+li.dataset.id);
});

function render() {
  materialsEl.querySelectorAll('button').forEach(b => b.classList.toggle('on', b.dataset.material === material));
  catalogEl.querySelectorAll('.sw').forEach(sw => {
    const id = +sw.dataset.id;
    sw.classList.toggle('on', selected.has(id));
    sw.classList.toggle('sug', suggested.some(c => c.id === id));
  });
  catalogEl.querySelectorAll('.series').forEach(sec => {
    const on = active.has(sec.dataset.series);
    sec.classList.toggle('inactive', !on);
    sec.classList.toggle('collapsed', !expanded.has(sec.dataset.series));
    const ids = colors.filter(c => c.series === sec.dataset.series);
    const n = ids.filter(c => selected.has(c.id)).length;
    sec.querySelector('.count').textContent = n ? `(${n}/${ids.length})` : `(${ids.length})`;
    sec.querySelector('[data-active]').classList.toggle('on', on);
  });
  drawPlots();
  drawHeat();
  drawSlice();
  drawRainbowBar();
  renderInfo();
}

