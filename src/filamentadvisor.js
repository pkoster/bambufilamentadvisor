// ---------- Advice: color-space coverage ----------
// A 3D grid in Lab, limited to what sRGB can display. Each grid point counts the distance to the
// nearest color in the set (selection + advice). We look for the colors that minimize the sum of those
// distances: add greedily, then swap until nothing improves further.
// Grid range. The grid consists of points in Lab; each point is flagged as inside sRGB or outside it (ext).
//   full = only points inside the sRGB gamut (what a screen can display)
//   ext  = sRGB + 20%: also points that fall inside the gamut enlarged by 1.2x (a*, b* and L* scaled up
//          from the neutral midpoint L=50)
// Whether a Lab color falls inside the sRGB gamut (what a screen can display). Also used to find, for a
// single L*, the edge of the gamut (see gamutBoundary), for the outline in the slice view.
function labToLinearRGB(L, a, b) {
  const inv = t => (t > 6 / 29 ? t ** 3 : 3 * (6 / 29) ** 2 * (t - 4 / 29));
  const fy = (L + 16) / 116, X = 0.95047 * inv(fy + a / 500), Y = inv(fy), Z = 1.08883 * inv(fy - b / 200);
  return [3.2404542 * X - 1.5371385 * Y - 0.4985314 * Z,
    -0.9692660 * X + 1.8760108 * Y + 0.0415560 * Z,
    0.0556434 * X - 0.2040259 * Y + 1.0572252 * Z];
}
function inGamut(L, a, b) {
  return labToLinearRGB(L, a, b).every(v => v > -0.002 && v < 1.002);
}
// Lab -> sRGB hex, to show the actual color of a grid point (instead of a distance).
// Assumes the point is already in gamut (see inGamut); otherwise it gets clamped to 0–255.
function labToHex(L, a, b) {
  const gamma = c => (c <= 0.0031308 ? c * 12.92 : 1.055 * c ** (1 / 2.4) - 0.055);
  return '#' + labToLinearRGB(L, a, b)
    .map(c => Math.round(Math.min(1, Math.max(0, gamma(c))) * 255).toString(16).padStart(2, '0'))
    .join('');
}

const GRID = (() => {
  const pts = [];
  for (let L = 0; L <= 100; L += 5) {
    for (let a = -128; a <= 128; a += 8) {
      for (let b = -136; b <= 136; b += 8) {
        if (inGamut(L, a, b)) pts.push({ L, a, b, ext: false });
        else if (inGamut(50 + (L - 50) / 1.2, a / 1.2, b / 1.2)) pts.push({ L, a, b, ext: true });
      }
    }
  }
  return pts;
})();
let rangeMode = 'ext'; // 120% (sRGB + 20%); must match the default in index.html
const IDX = {
  full: Int32Array.from(GRID.map((g, i) => (g.ext ? -1 : i)).filter(i => i >= 0)),
  ext: Int32Array.from(GRID, (_, i) => i),
};
const currentGridIdx = () => IDX[rangeMode];

// Edge of the sRGB gamut at one fixed L*, as a polygon: for every angle, the largest chroma that's still
// in gamut (binary search). Used in the slice view to show what actually exists as a color at that level,
// instead of just the coarse grid points.
const gamutBoundaryCache = new Map();
function gamutBoundary(L) {
  const key = Math.round(L);
  if (gamutBoundaryCache.has(key)) return gamutBoundaryCache.get(key);
  const pts = [];
  for (let deg = 0; deg < 360; deg += 5) {
    const rad = deg * Math.PI / 180, ca = Math.cos(rad), sb = Math.sin(rad);
    let lo = 0, hi = 200;
    for (let i = 0; i < 22; i++) {
      const mid = (lo + hi) / 2;
      if (inGamut(key, mid * ca, mid * sb)) lo = mid; else hi = mid;
    }
    pts.push({ a: lo * ca, b: lo * sb });
  }
  gamutBoundaryCache.set(key, pts);
  return pts;
}


// Distances from a color to every grid point, computed once per distance metric.
function gridDist(c) {
  c._d = c._d || {};
  return c._d[metric] || (c._d[metric] = Float32Array.from(GRID, g => dist(c, g)));
}

// Per grid point, the distance to the nearest color in the list (Infinity if the list is empty).
function nearestOf(list, idx = currentGridIdx()) {
  const m = new Float32Array(GRID.length).fill(Infinity);
  for (const c of list) { const d = gridDist(c); for (const i of idx) if (d[i] < m[i]) m[i] = d[i]; }
  return m;
}

// Sum of the distances to the nearest color (Infinity if the set is empty).
function coverageCost(list, idx = currentGridIdx()) {
  const ds = list.map(gridDist);
  let sum = 0;
  for (const i of idx) {
    let m = Infinity;
    for (const d of ds) if (d[i] < m) m = d[i];
    sum += m;
  }
  return sum;
}
const coverageMean = list => { const idx = currentGridIdx(); return coverageCost(list, idx) / idx.length; };

// The advice algorithm is user-selectable (see the "Algorithm" option): greedy is the original, fast
// approach; multi-start adds randomized restarts and a pairwise-swap cleanup; annealing does a randomized
// search that can accept temporarily worse moves to escape local optima; k-center optimizes a different
// goal entirely (the worst gap, instead of the total gap).
let algorithm = 'greedy';

function advise(n) {
  if (n <= 0) return [];
  if (algorithm === 'kcenter') return adviseKCenter(n);
  if (algorithm === 'multistart') return adviseMultiStart(n);
  if (algorithm === 'annealing') return adviseAnnealing(n);
  return adviseGreedy(n);
}

// Cost/candidate-search helpers shared by the greedy and multi-start algorithms. `near` is, per grid
// point, the distance to the nearest already-chosen color.
function coverageHelpers(pool, idx) {
  const costWith = (near, c) => {
    const d = gridDist(c);
    let s = 0;
    for (const i of idx) s += d[i] < near[i] ? d[i] : near[i];
    return s;
  };
  const bestAmong = (near, exclude) => {
    let bc = null, bs = Infinity;
    for (const c of pool) {
      if (exclude.includes(c)) continue;
      const s = costWith(near, c);
      if (s < bs) { bs = s; bc = c; }
    }
    return [bc, bs];
  };
  return { costWith, bestAmong };
}

// 1-opt refinement: swap one pick at a time for the best candidate given the rest. Mutates `picks`.
function oneOptRefine(picks, base, idx, bestAmong, costWith) {
  for (let round = 0; round < 20; round++) {
    let improved = false;
    for (let i = 0; i < picks.length; i++) {
      const rest = base.concat(picks.filter((_, j) => j !== i));
      const near = nearestOf(rest, idx);
      const cur = costWith(near, picks[i]);
      const saved = picks[i];
      picks[i] = null; // so the current pick is a candidate again too
      const [c, s] = bestAmong(near, picks);
      picks[i] = s < cur - 1e-6 ? c : saved;
      if (picks[i] !== saved) improved = true;
    }
    if (!improved) break;
  }
}

// 2-point refinement: reconsider a *pair* of picks jointly instead of one at a time. Catches cases where
// no single swap helps but changing two picks together would — plain 1-opt can never find that, since it
// only ever looks at one slot in isolation. This is the expensive step (each pair check costs roughly as
// much as a full greedy build), so it's kept deliberately bounded: only a couple of rounds, and only a
// sampled subset of pairs when there are many picks, rather than every combination.
const TWO_POINT_ROUNDS = 2;
const TWO_POINT_MAX_PAIRS = 80;
function twoPointRefine(picks, base, idx, bestAmong, costWith) {
  let improved = true, round = 0;
  while (improved && round++ < TWO_POINT_ROUNDS) {
    improved = false;
    let pairs = [];
    for (let i = 0; i < picks.length; i++) for (let j = i + 1; j < picks.length; j++) pairs.push([i, j]);
    if (pairs.length > TWO_POINT_MAX_PAIRS) {
      // Too many combinations to check exhaustively; sample an even spread instead of every pair.
      const step = pairs.length / TWO_POINT_MAX_PAIRS;
      pairs = Array.from({ length: TWO_POINT_MAX_PAIRS }, (_, k) => pairs[Math.floor(k * step)]);
    }
    for (const [i, j] of pairs) {
      const savedI = picks[i], savedJ = picks[j];
      const before = coverageCost(base.concat(picks), idx);
      picks[i] = null; picks[j] = null;
      const near1 = nearestOf(base.concat(picks.filter(Boolean)), idx);
      picks[i] = bestAmong(near1, picks)[0];
      const near2 = nearestOf(base.concat(picks.filter(Boolean)), idx);
      picks[j] = bestAmong(near2, picks)[0];
      const after = coverageCost(base.concat(picks), idx);
      if (after < before - 1e-6) improved = true;
      else { picks[i] = savedI; picks[j] = savedJ; }
    }
  }
}

// The original approach: build up greedily (always add whichever candidate reduces the total gap the
// most), then clean up with 1-opt swaps. Fast, but can get stuck — greedy commits early to choices that
// block a better overall layout, and 1-opt only escapes local optima that a *single* swap can fix.
function adviseGreedy(n) {
  const base = visibleSel();
  const pool = candidatePool();
  n = Math.min(n, pool.length);
  const idx = currentGridIdx();
  const { costWith, bestAmong } = coverageHelpers(pool, idx);
  const picks = [];
  while (picks.length < n) picks.push(bestAmong(nearestOf(base.concat(picks), idx), picks)[0]);
  oneOptRefine(picks, base, idx, bestAmong, costWith);
  return picks.sort((x, y) => y.L - x.L);
}

// Multiple randomized greedy builds (GRASP-style: pick randomly among the current top few candidates,
// instead of always the single best), each cleaned up with the cheap 1-opt pass; keep whichever run ends
// up with the lowest total gap. The very first run is the plain deterministic greedy build, so this option
// can never do worse than plain greedy — only potentially better. The more expensive 2-point cleanup runs
// only once, on the best restart, rather than on every one of them — doing it per restart is what made an
// early version of this take 20+ seconds. Fewer restarts are used for larger requests, for the same reason.
const GRASP_TOP_K = 3;
function adviseMultiStart(n) {
  const base = visibleSel();
  const pool = candidatePool();
  n = Math.min(n, pool.length);
  if (n === 0) return [];
  const idx = currentGridIdx();
  const { costWith, bestAmong } = coverageHelpers(pool, idx);
  const restarts = n <= 15 ? 8 : n <= 30 ? 5 : 3;

  let bestPicks = null, bestScore = Infinity;
  for (let run = 0; run < restarts; run++) {
    const picks = [];
    while (picks.length < n) {
      const near = nearestOf(base.concat(picks), idx);
      if (run === 0) {
        picks.push(bestAmong(near, picks)[0]);
      } else {
        const scored = pool.filter(c => !picks.includes(c)).map(c => [c, costWith(near, c)]).sort((a, b) => a[1] - b[1]);
        const topK = scored.slice(0, Math.min(GRASP_TOP_K, scored.length));
        picks.push(topK[Math.floor(Math.random() * topK.length)][0]);
      }
    }
    oneOptRefine(picks, base, idx, bestAmong, costWith);
    const score = coverageCost(base.concat(picks), idx);
    if (score < bestScore) { bestScore = score; bestPicks = picks; }
  }
  if (bestPicks.length <= 60) twoPointRefine(bestPicks, base, idx, bestAmong, costWith); // skip for very long lists
  return bestPicks.sort((x, y) => y.L - x.L);
}

// Simulated annealing: start from the plain greedy result, then repeatedly try replacing one random pick
// with one random unpicked candidate. A move that improves things is always kept; a move that makes things
// worse is still kept sometimes, with a probability that shrinks as the "temperature" cools down over the
// run. That occasional acceptance of a worse move is what lets it climb out of local optima that greedy's
// hill-climbing (1-opt) can never leave, since 1-opt only ever accepts a strict improvement. The best set
// seen across the whole run is returned, so — like multi-start — this can never end up worse than the
// plain greedy result it started from.
//
// Neighbor moves are random rather than "best of all candidates" on purpose: picking a random unpicked
// color is O(1), versus scanning the whole candidate pool (as the greedy/multi-start algorithms do), so
// this can afford several thousand small steps instead of a handful of expensive exhaustive ones.
function adviseAnnealing(n) {
  const base = visibleSel();
  const pool = candidatePool();
  n = Math.min(n, pool.length);
  if (n === 0) return [];
  if (pool.length <= n) return adviseGreedy(n); // no unpicked candidates left to explore with
  const idx = currentGridIdx();
  const scoreOf = list => coverageCost(list, idx) / idx.length; // mean ΔE, keeps the temperature intuitive

  let current = adviseGreedy(n).slice();
  let currentScore = scoreOf(base.concat(current));
  let best = current.slice(), bestScore = currentScore;
  const pickedSet = new Set(current);
  const randomSwap = () => {
    const i = Math.floor(Math.random() * n);
    let c;
    do { c = pool[Math.floor(Math.random() * pool.length)]; } while (pickedSet.has(c));
    return [i, c];
  };

  // Fewer steps for larger requests, so this stays responsive; each step costs roughly one coverage scan.
  const iterations = n <= 15 ? 3000 : n <= 30 ? 1500 : 600;
  // Calibrate the starting temperature from the actual size of a handful of random moves here, rather than
  // guessing a fraction of the objective's absolute value — the two aren't reliably related (an early,
  // fixed-fraction guess left the search too "hot" for far too long, so it barely did better than a random
  // walk until it was nearly out of iterations, and never actually escaped the greedy starting point).
  let sampleTotal = 0;
  for (let s = 0; s < 30; s++) {
    const [i, c] = randomSwap();
    const trial = current.slice(); trial[i] = c;
    sampleTotal += Math.abs(scoreOf(base.concat(trial)) - currentScore);
  }
  const T0 = Math.max(1e-6, sampleTotal / 30);
  const coolingRate = Math.pow(0.01, 1 / iterations);
  let T = T0;

  for (let iter = 0; iter < iterations; iter++) {
    const [i, c] = randomSwap();
    const trial = current.slice();
    trial[i] = c;
    const trialScore = scoreOf(base.concat(trial));
    const delta = trialScore - currentScore;
    if (delta < 0 || Math.random() < Math.exp(-delta / T)) {
      pickedSet.delete(current[i]);
      pickedSet.add(c);
      current = trial;
      currentScore = trialScore;
      if (currentScore < bestScore) { bestScore = currentScore; best = current.slice(); }
    }
    T *= coolingRate;
  }
  return best.sort((x, y) => y.L - x.L);
}

// K-center: instead of minimizing the total gap, minimize the *worst* gap. At each step, find the
// grid point that is currently covered worst, and add whichever candidate sits closest to that specific
// point. Classic, efficient (no need to scan the whole grid for every candidate, unlike the two algorithms
// above), and tends to favor extremes/outliers earlier than the coverage-based algorithms do.
function adviseKCenter(n) {
  const base = visibleSel();
  const pool = candidatePool();
  n = Math.min(n, pool.length);
  const idx = currentGridIdx();
  const anchor = base.length ? base : [{ L: 50, a: 0, b: 0 }]; // neutral midpoint if nothing is selected yet
  const near = nearestOf(anchor, idx);
  const remaining = new Set(pool);
  const picks = [];
  while (picks.length < n) {
    let worst = idx[0], worstVal = -1;
    for (const i of idx) if (near[i] > worstVal) { worstVal = near[i]; worst = i; }
    let bestC = null, bestD = Infinity;
    for (const c of remaining) {
      const d = dist(c, GRID[worst]);
      if (d < bestD) { bestD = d; bestC = c; }
    }
    if (!bestC) break;
    picks.push(bestC);
    remaining.delete(bestC);
    const dC = gridDist(bestC);
    for (const i of idx) if (dC[i] < near[i]) near[i] = dC[i];
  }
  return picks.sort((x, y) => y.L - x.L);
}

