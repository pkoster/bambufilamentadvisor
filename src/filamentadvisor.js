function drawHeat() {
  const set = visibleSel().concat(suggested);
  const legendMax = document.getElementById('legendMax');
  // The heatmap always shows only the sRGB gamut (100%), regardless of the chosen range: that range
  // (100% or +20%) does determine which grid points count toward the optimization (see advise()/coverageCost()).
  const idx = IDX.full;
  const near = set.length ? nearestOf(set, idx) : null;
  // Per grid point, also which color is the nearest one (for the tooltip).
  const who = [];
  if (near) for (const i of idx) { let bi = 0; set.forEach((c, k) => { if (gridDist(c)[i] < gridDist(set[bi])[i]) bi = k; }); who[i] = set[bi]; }
  const cellsAB = new Map(), cellsCL = new Map();
  if (near) {
    for (const i of idx) {
      const g = GRID[i];
      const add = (map, key, x, y, w, h) => {
        const c = map.get(key) || (map.set(key, { x, y, w, h, sum: 0, max: 0, n: 0, worst: -1, votes: new Map() }), map.get(key));
        c.sum += near[i]; c.n++;
        if (near[i] > c.max || c.worst < 0) { c.max = near[i]; c.worst = i; }
        c.votes.set(who[i], (c.votes.get(who[i]) || 0) + 1);
      };
      add(cellsAB, g.a + ',' + g.b, g.a - 4, g.b - 4, 8, 8);
      const k = Math.floor(Math.hypot(g.a, g.b) / 8);
      add(cellsCL, k + ',' + g.L, k * 8, g.L - 2.5, 8, 5);
    }
  }
  const val = c => (heatMode === 'max' ? c.max : c.sum / c.n);
  // Fixed scale per distance metric, so colors stay comparable across selections and ranges; larger
  // values get the darkest color.
  const vmax = HEAT_MAX[metric];
  let seen = 0;
  for (const m of [cellsAB, cellsCL]) for (const c of m.values()) seen = Math.max(seen, val(c));
  legendMax.textContent = near ? `≥ ${vmax} (now max ${seen.toFixed(0)})` : `≥ ${vmax}`;
  const label = METRIC_LABEL[metric];

  const rects = (plot, cells) => g => {
    const [x0, x1] = plot.xr, [y0, y1] = plot.yr;
    for (const c of cells.values()) {
      const xa = Math.max(c.x, x0), xb = Math.min(c.x + c.w, x1), ya = Math.max(c.y, y0), yb = Math.min(c.y + c.h, y1);
      if (xb <= xa || yb <= ya) continue;
      const r = el('rect', { x: plot.sx(xa), y: plot.sy(yb), width: plot.sx(xb) - plot.sx(xa), height: plot.sy(ya) - plot.sy(yb), fill: rampColor(val(c) / (vmax || 1)) }, g);
      // max: nearest color of the worst point; average: the color that's nearest most often in the cell
      const nearest = heatMode === 'max' ? who[c.worst] : [...c.votes].sort((p, q) => q[1] - p[1])[0][0];
      const w = GRID[c.worst];
      el('title', {}, r).textContent = `${label} ${val(c).toFixed(1)}\nNearest: ${nearest.name} (${nearest.code}, ${nearest.series})`
        + (heatMode === 'max' ? `\nWorst point: L*=${w.L} a*=${w.a} b*=${w.b}` : '');
    }
  };
  drawFrame(plotABh, g => { rects(plotABh, cellsAB)(g); abGuides(plotABh)(g); });
  drawFrame(plotCLh, rects(plotCLh, cellsCL));
  if (!near) {
    for (const p of [plotABh, plotCLh]) el('text', { x: W / 2, y: H / 2, 'text-anchor': 'middle' }, p.svg).textContent = 'Select colors to see the coverage';
    return;
  }
  for (const plot of [plotABh, plotCLh]) {
    const proj = plot === plotABh ? c => [plot.sx(c.a), plot.sy(c.b)] : c => [plot.sx(c.C), plot.sy(c.L)];
    drawCandidates(plot, proj, 4.5);
    for (const c of set) {
      const [x, y] = proj(c);
      const sug = suggested.includes(c);
      const d = el('circle', { class: sug ? 'adv' : 'pt', 'data-id': c.id, cx: x, cy: y, r: sug ? 6 : 4.5, fill: '#' + c.hex }, plot.svg);
      el('title', {}, d).textContent = tip(c);
    }
  }
}

