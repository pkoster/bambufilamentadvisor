const materialsEl = document.getElementById('materials');
// The most commonly used materials are always shown; the rest only appear after expanding. The active
// material always stays visible, even if it belongs to the collapsible group.
const MATERIALS_ALWAYS = ['PLA', 'PETG', 'ABS', 'TPU'];
let materialsExpanded = false;
function buildMaterialsUI() {
  materialsEl.replaceChildren();
  const hidden = [];
  for (const m of materials) {
    const b = document.createElement('button');
    b.dataset.material = m;
    b.textContent = m;
    b.title = `${catalogAll.filter(e => e.material === m).length} colors`;
    if (!materialsExpanded && !MATERIALS_ALWAYS.includes(m) && m !== material) { hidden.push(m); continue; }
    materialsEl.appendChild(b);
  }
  if (materialsExpanded || hidden.length) {
    const t = document.createElement('button');
    t.dataset.materialsToggle = '1';
    t.textContent = materialsExpanded ? 'less' : `more (${hidden.length})`;
    t.title = materialsExpanded ? 'Show only the most-used materials' : 'Show the other materials too';
    materialsEl.appendChild(t);
  }
}
materialsEl.addEventListener('click', e => {
  if (e.target.closest('[data-materials-toggle]')) {
    materialsExpanded = !materialsExpanded;
    buildMaterialsUI();
    render();
    return;
  }
  const b = e.target.closest('[data-material]');
  if (!b || b.dataset.material === material) return;
  setMaterial(b.dataset.material);
  document.getElementById('search').value = '';
  catalogEl.classList.remove('searching');
  buildCatalogUI();
  render();
});

