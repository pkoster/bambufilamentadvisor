function loadColors(catalog) {
  saveSelection();
  catalogAll = catalog;
  materials = [...new Set(catalog.map(e => e.material))];
  if (!materials.includes(material)) material = materials[0];
  buildForMaterial();
}

function setMaterial(m) {
  if (m === material) return;
  saveSelection();
  material = m;
  buildForMaterial();
}

function buildForMaterial() {
  colors = []; seriesList = []; skipped = 0; multiByKey = new Map();
  for (const e of catalogAll) {
    if (e.material !== material) continue;
    if (e.hex.length !== 1) { skipped++; multiByKey.set(e.code, e); multiByKey.set(e.sku.toUpperCase(), e); continue; }
    const lab = hexToLab(e.hex[0]);
    colors.push({ id: colors.length, series: e.series, code: e.code, sku: e.sku, name: e.name, nl: e.nl, hex: e.hex[0], ...lab, C: Math.hypot(lab.a, lab.b) });
    if (!seriesList.includes(e.series)) seriesList.push(e.series);
  }
  // Known flagship series first; the rest in catalog order. Nothing is active or expanded by default.
  const first = ['PLA Basic', 'PLA Matte', 'PLA Pure', 'PETG Basic', 'PETG Matte', 'PETG HF'];
  const rank = s => (first.includes(s) ? first.indexOf(s) : first.length);
  seriesList.sort((a, b) => rank(a) - rank(b));
  selected.clear();
  const keep = selByMaterial.get(material) || new Set();
  colors.forEach(c => keep.has(c.code) && selected.add(c.id));
  ignored.clear();
  const skip = ignoredByMaterial.get(material) || new Set();
  colors.forEach(c => skip.has(c.code) && !selected.has(c.id) && ignored.add(c.id));
  suggested = [];
}
